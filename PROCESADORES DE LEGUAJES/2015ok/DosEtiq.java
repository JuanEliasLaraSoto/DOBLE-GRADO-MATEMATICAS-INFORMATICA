public class DosEtiq {
    protected String v;
    protected String f;
    public DosEtiq(String verdadero, String falso){
        v=verdadero;
        f=falso;
    }

    public String getV() {
        return this.v;
    }

    public void setV(String v) {
        this.v = v;
    }

    public String getF() {
        return this.f;
    }

    public void setF(String f) {
        this.f = f;
    }

}
